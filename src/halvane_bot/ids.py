"""Role and channel ids by stable key, read from config/ids.yaml.

Code and embeds refer to roles and channels by key (`station_chief`, `ranks_explained`), never by raw id.
Keys are derived from names once and then kept by id, so renaming a role in Discord does not break them.
"""
from __future__ import annotations

import re
import unicodedata
from dataclasses import dataclass
from pathlib import Path
from typing import Iterable, Mapping

import yaml


class UnknownIdError(KeyError):
    """A role or channel key that is not in ids.yaml."""

    def __str__(self) -> str:  # KeyError quotes its message; keep it readable
        return str(self.args[0])


@dataclass(frozen=True)
class IdRegistry:
    guild_id: int
    roles: Mapping[str, int]
    channels: Mapping[str, int]

    def role(self, key: str) -> int:
        try:
            return self.roles[key]
        except KeyError:
            raise UnknownIdError(f"unknown role key '{key}' (not in ids.yaml)") from None

    def channel(self, key: str) -> int:
        try:
            return self.channels[key]
        except KeyError:
            raise UnknownIdError(f"unknown channel key '{key}' (not in ids.yaml)") from None


def load_ids(path: Path) -> IdRegistry:
    raw = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    return IdRegistry(
        guild_id=int(raw.get("guild_id", 0)),
        roles={str(k): int(v) for k, v in (raw.get("roles") or {}).items()},
        channels={str(k): int(v) for k, v in (raw.get("channels") or {}).items()},
    )


def slug(name: str) -> str:
    """'Packing · NCO' -> 'packing_nco', '[──── GRADE ────]' -> 'sep_grade', '— High Ranks' -> 'label_high_ranks'."""
    stripped = name.strip()
    prefix = ""
    if stripped.startswith("[") and stripped.endswith("]"):
        prefix = "sep_"
    elif stripped.startswith(("—", "–")):
        prefix = "label_"
    text = unicodedata.normalize("NFKD", stripped).encode("ascii", "ignore").decode().lower()
    text = re.sub(r"[^a-z0-9]+", "_", text).strip("_")
    return prefix + (text or "unnamed")


# Discord channel types we label when two channels would get the same key.
CHANNEL_KIND = {0: "text", 2: "voice", 4: "category", 5: "announcement", 13: "stage", 15: "forum", 16: "media"}
KIND_PRIORITY = {"role": 0, "text": 0, "announcement": 0, "forum": 0, "media": 0, "category": 1, "voice": 2, "stage": 2}


def assign_keys(items: Iterable[tuple[int, str, str]], existing: Mapping[str, int]) -> dict[str, int]:
    """items: (id, name, kind). Keep existing keys for known ids; derive new ones, de-duplicating by kind."""
    by_id = {v: k for k, v in existing.items()}
    result: dict[str, int] = {}
    pending: list[tuple[int, str, str]] = []
    for item_id, name, kind in items:
        if item_id in by_id:
            result[by_id[item_id]] = item_id
        else:
            pending.append((item_id, name, kind))
    # Text-like channels get the plain key; a voice channel with the same name gets "_voice".
    pending.sort(key=lambda item: KIND_PRIORITY.get(item[2], 3))
    for item_id, name, kind in pending:
        key = slug(name)
        if kind == "category":
            key = "cat_" + key
        if key in result:
            key = f"{key}_{kind}"
        n = 2
        base = key
        while key in result:
            key = f"{base}_{n}"
            n += 1
        result[key] = item_id
    return result


def render_ids_yaml(guild_id: int, roles: dict[str, int], channels: dict[str, int],
                    role_names: Mapping[int, str], channel_names: Mapping[int, str]) -> str:
    """YAML with each line commented with the current Discord name (PyYAML can't write comments)."""
    out = [
        "# Generated by `python -m halvane_bot export-ids`. Keys are stable; names in comments are informative.",
        "# Edit a key only together with every embed that uses it.",
        f'guild_id: "{guild_id}"',
        "",
        "roles:",
    ]
    out += [f'  {k}: "{v}"  # {role_names.get(v, "")}' for k, v in roles.items()]
    out += ["", "channels:"]
    out += [f'  {k}: "{v}"  # {channel_names.get(v, "")}' for k, v in channels.items()]
    return "\n".join(out) + "\n"
